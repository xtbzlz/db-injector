static iTVPFunctionExporter *g_exporter = NULL;

HRESULT __stdcall V2Link(iTVPFunctionExporter *exporter)
{
    g_exporter = exporter;
    // resolve exporter vtable method: object memory = [vptr][...]; vptr points
    // to the real function table [QueryFunctions, QueryFunctionsByNarrowString, ...]
    void **vtbl = *(void ***)exporter;
    QueryNarrowFn qn = (QueryNarrowFn)vtbl[1];
    const char *names[6] = {
        "iTJSDispatch2 * ::TVPGetScriptDispatch()",
        "void ::TVPExecuteExpression(const ttstr &,tTJSVariant *)",
        "tTJSVariantString * ::TJSAllocVariantString(const tjs_char *)",
        "void ::TVPDoTryBlock(tTVPTryBlockFunction,tTVPCatchBlockFunction,tTVPFinallyBlockFunction,void *)",
        "void ::TVPExecuteScript(const ttstr &,const ttstr &,tjs_int,tTJSVariant *)",
        "void ::TVPExecuteStorage(const ttstr &,tTJSVariant *,bool,const tjs_char *)",
    };
    void *funcs[6] = { NULL, NULL, NULL, NULL, NULL, NULL };
    qn(exporter, names, funcs, 6);
    g_getScriptDispatch = (GetScriptDispatchFn)funcs[0];
    g_executeExpression = (ExecuteExpressionFn)funcs[1];
    g_allocVariantString = (AllocVariantStringFn)funcs[2];
    g_doTryBlock = (DoTryBlockFn)funcs[3];
    g_executeScript = (ExecuteScriptFn)funcs[4];
    g_executeStorage = (ExecuteStorageFn)funcs[5];

    // determine game dir (parent of the exe)
    wchar_t path[1024];
    DWORD n = GetModuleFileNameW(NULL, path, 1024);
    if (n > 0 && n < 1024) {
        // strip file name -> exe dir
        while (n > 0 && path[n - 1] != '\\') n--;
        while (n > 0 && path[n - 1] == '\\') n--;
        if (n > 0) {
            memcpy(g_logDir, path, n * 2);
            g_logDir[n] = 0;
        }
    }

    logStr("=== tbc_bridge V2Link ===\n");
    char buf[512];
    _snprintf(buf, sizeof(buf),
        "exporter=%p\nTVPGetScriptDispatch=%p TVPExecuteScript=%p TJSAllocVariantString=%p TVPDoTryBlock=%p\n",
        exporter, funcs[0], funcs[1], funcs[2], funcs[3]);
    logStr(buf);

    // hidden window on the main thread
    WNDCLASSW wc;
    memset(&wc, 0, sizeof(wc));
    wc.lpfnWndProc = bridgeWndProc;
    wc.lpszClassName = L"tbc_bridge_wnd";
    if (RegisterClassW(&wc)) {
        g_bridgeHwnd = CreateWindowExW(0, L"tbc_bridge_wnd", L"tbc", 0, 0, 0, 0, 0, NULL, NULL, NULL, NULL);
        if (!g_bridgeHwnd) logStr("CreateWindowExW failed\n");
    } else {
        logStr("RegisterClassW failed\n");
    }

    HANDLE th = CreateThread(NULL, 0, pipeThread, NULL, 0, NULL);
    if (th) CloseHandle(th);
    return S_OK;
}

HRESULT __stdcall V2Unlink(void)
{
    if (g_bridgeHwnd) DestroyWindow(g_bridgeHwnd);
    logStr("=== tbc_bridge V2Unlink ===\n");
    return S_OK;
}





