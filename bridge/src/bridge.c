// tb_bridge.c
// krkrz (KiriKiri Z) plugin bridge for the D&B trainer.
// Loaded by the engine via V2Link (undecorated, __stdcall). Hosts a named
// pipe server; executes TJS code in the game process on the main thread.
// Build: zig cc -target i386-windows-gnu -shared -Wl,--kill-at -O2 -o tb_bridge.dll tb_bridge.c
