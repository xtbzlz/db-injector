// wrapper template: user code is inserted at @@USER@@.
// If <gamedir>\tbc_wrapper.txt exists it overrides the built-in template
// (lets us iterate on the wrapper without rebuilding/restarting).
// The script stores its result into global.__tbc_result__; the plugin reads
// it back via PropGet, which avoids depending on TJS's block-result feature.
static const char *DEFAULT_WRAPPER =
    "var __tbc_r;try{__tbc_r=(function(){@@USER@@"
    "})();}catch(__tbc_e){__tbc_r='!!EXCEPTION!! '+__tbc_e;}"
    "if(__tbc_r==null){__tbc_r='undefined';}"
    "global.__tbc_result__=__tbc_r.toString();";

static char *loadWrapperTemplate(void)
{
    if (!g_logDir[0]) return _strdup(DEFAULT_WRAPPER);
    wchar_t path[1100];
    wsprintfW(path, L"%ls\\tbc_wrapper.txt", g_logDir);
    FILE *f = _wfopen(path, L"rb");
    if (!f) return _strdup(DEFAULT_WRAPPER);
    fseek(f, 0, SEEK_END);
    long sz = ftell(f);
    fseek(f, 0, SEEK_SET);
    char *buf = (char *)malloc((size_t)sz + 1);
    if (!buf) { fclose(f); return _strdup(DEFAULT_WRAPPER); }
    size_t got = fread(buf, 1, (size_t)sz, f);
    fclose(f);
    buf[got] = 0;
    return buf;
}

static char *buildWrapper(const char *code, int codeLen)
{
    char *tmpl = loadWrapperTemplate();
    if (!tmpl) return NULL;
    char *marker = strstr(tmpl, "@@USER@@");
    if (!marker) {
        // no marker: treat whole template as prefix and append code
        int tl = (int)strlen(tmpl);
        char *out = (char *)malloc(tl + codeLen + 1);
        if (out) {
            memcpy(out, tmpl, tl);
            memcpy(out + tl, code, codeLen);
            out[tl + codeLen] = 0;
        }
        free(tmpl);
        return out;
    }
    int preLen = (int)(marker - tmpl);
    int postLen = (int)strlen(marker + 8);
    char *out = (char *)malloc(preLen + codeLen + postLen + 1);
    if (out) {
        memcpy(out, tmpl, preLen);
        memcpy(out + preLen, code, codeLen);
        memcpy(out + preLen + codeLen, marker + 8, postLen);
        out[preLen + codeLen + postLen] = 0;
    }
    free(tmpl);
    return out;
}

typedef struct _EvalOutcome {
    int ok;
    char *result; // malloc'd utf8 (OK case)
    char *error;  // malloc'd utf8 (ERR case)
} EvalOutcome;

// iTJSDispatch2::PropGet (vtable[4], cdecl, this first)
typedef int (__cdecl *DispatchPropGetFn)(void *self, unsigned long flag,
    const wchar_t *membername, unsigned long *hint, Variant *result, void *objthis);

// iTJSDispatch2::EnumMembers (vtable[14], cdecl, this first)
typedef int (__cdecl *DispatchEnumMembersFn)(void *self, unsigned long flag,
    void *callback, void *objthis);

static char *readGlobalResult(void)
{
    void *g = g_getScriptDispatch();
    if (!g) return _strdup("(no global)");
    void **vtbl = *(void ***)g;
    DispatchPropGetFn propGet = (DispatchPropGetFn)vtbl[4];
    Variant rv;
    memset(&rv, 0, sizeof(rv));
    unsigned long hint = 0;
    int rc = propGet(g, 0, L"__tbc_result__", &hint, &rv, NULL);
    if (rc != 0) return _strdup("(propget failed)");
    if (rv.vt != TVT_STRING || !rv.u.string) return _strdup("(non-string)");
    VSString *vs = rv.u.string;
    const wchar_t *dp = vs->LongString ? vs->LongString : vs->ShortString;
    int n = vs->Length;
    if (n < 0) n = 0;
    return utf16ToUtf8(dp, n);
}

static void doEval(const char *codeUtf8, int codeLen, EvalOutcome *outcome)
{
    outcome->ok = 0;
    outcome->result = NULL;
    outcome->error = NULL;
    if (!g_getScriptDispatch || !g_executeExpression || !g_allocVariantString || !g_doTryBlock) {
        outcome->error = _strdup("engine functions not resolved");
        return;
    }
    if (g_getScriptDispatch() == NULL) {
        outcome->error = _strdup("TJS engine not ready");
        return;
    }
    // expression mode: user code must be a single expression
    wchar_t *w16 = utf8ToUtf16(codeUtf8, codeLen);
    if (!w16) { outcome->error = _strdup("no memory"); return; }
    VSString *vs = g_allocVariantString(w16);
    free(w16);
    if (!vs) { outcome->error = _strdup("TJSAllocVariantString failed"); return; }

    TryData data;
    memset(&data, 0, sizeof(data));
    data.ttstr.Ptr = vs;
    g_doTryBlock((void *)&tryBlock, (void *)&catchBlock, NULL, &data);

    if (data.error) {
        outcome->error = data.error;
        return;
    }
    Variant *r = &data.result;
    if (r->vt == TVT_STRING && r->u.string) {
        VSString *rvs = r->u.string;
        const wchar_t *dp = rvs->LongString ? rvs->LongString : rvs->ShortString;
        int n = rvs->Length;
        if (n < 0) n = 0;
        outcome->result = utf16ToUtf8(dp, n);
        outcome->ok = 1;
    } else if (r->vt == TVT_INTEGER) {
        char buf[32];
        snprintf(buf, sizeof(buf), "%lld", (long long)r->u.integer);
        outcome->result = _strdup(buf);
        outcome->ok = 1;
    } else if (r->vt == TVT_REAL) {
        char buf[64];
        snprintf(buf, sizeof(buf), "%g", r->u.real);
        outcome->result = _strdup(buf);
        outcome->ok = 1;
    } else if (r->vt == TVT_VOID) {
        outcome->result = _strdup("undefined");
        outcome->ok = 1;
    } else {
        outcome->result = _strdup("[non-string result]");
        outcome->ok = 1;
    }
}

// script-mode eval: executes via TVPExecuteScript(name, script, mode, result),
// so full TJS syntax (for/if/try-catch/arrays) works without storage files.
static void doEvalScript(const char *codeUtf8, int codeLen, EvalOutcome *outcome)
{
    outcome->ok = 0;
    outcome->result = NULL;
    outcome->error = NULL;
    if (!g_executeScript || !g_allocVariantString || !g_doTryBlock) {
        outcome->error = _strdup("engine functions not resolved");
        return;
    }
    if (g_getScriptDispatch() == NULL) {
        outcome->error = _strdup("TJS engine not ready");
        return;
    }
    // execute via TVPExecuteScript(name, script, TJS_SCRIPT_NORMAL=0, result):
    // the script text is passed directly; no storage file or path involved.
    wchar_t *w16 = utf8ToUtf16(codeUtf8, codeLen);
    if (!w16) { outcome->error = _strdup("no memory"); return; }
    VSString *vsCode = g_allocVariantString(w16);
    free(w16);
    if (!vsCode) { outcome->error = _strdup("TJSAllocVariantString failed"); return; }
    VSString *vsName = g_allocVariantString(L"tbc_script");
    if (!vsName) { outcome->error = _strdup("TJSAllocVariantString failed"); return; }

    TryData data;
    memset(&data, 0, sizeof(data));
    data.ttstr.Ptr = vsCode;   // script text
    data.name.Ptr = vsName;    // script name (for error messages)
    g_doTryBlock((void *)&tryBlockScript, (void *)&catchBlock, NULL, &data);

    if (data.error) {
        outcome->error = data.error;
        return;
    }
    Variant *r = &data.result;
    if (r->vt == TVT_STRING && r->u.string) {
        VSString *rvs = r->u.string;
        const wchar_t *dp = rvs->LongString ? rvs->LongString : rvs->ShortString;
        int n = rvs->Length;
        if (n < 0) n = 0;
        outcome->result = utf16ToUtf8(dp, n);
        outcome->ok = 1;
    } else if (r->vt == TVT_INTEGER) {
        char buf[32];
        snprintf(buf, sizeof(buf), "%lld", (long long)r->u.integer);
        outcome->result = _strdup(buf);
        outcome->ok = 1;
    } else if (r->vt == TVT_REAL) {
        char buf[64];
        snprintf(buf, sizeof(buf), "%g", r->u.real);
        outcome->result = _strdup(buf);
        outcome->ok = 1;
    } else if (r->vt == TVT_VOID) {
        outcome->result = _strdup("undefined");
        outcome->ok = 1;
    } else {
        outcome->result = _strdup("[non-string result]");
        outcome->ok = 1;
    }
}

// ---------------------------------------------------------------------------
// LIST: enumerate registry `o` members (keys = Japanese identifiers) and
// attach each member's `name` (runtime/localized) + `id` when present.
// Implements a minimal iTJSDispatch2 (only FuncCall) used as EnumMembers
// callback; collects keys in pass 1, then PropGets name/id per key.
// ---------------------------------------------------------------------------
#define TJS_ENUM_NO_VALUE 0x00100000

typedef struct _KeyList {
    wchar_t **keys;   // heap strings
    int count;
    int cap;
} KeyList;

typedef struct _MiniDispatch {
    void **vtbl;
} MiniDispatch;

static void appendKey(KeyList *kl, const wchar_t *s, int n)
{
    if (kl->count >= kl->cap) {
        int nc = kl->cap ? kl->cap * 2 : 512;
        wchar_t **nk = (wchar_t **)realloc(kl->keys, (size_t)nc * sizeof(wchar_t *));
        if (!nk) return;
        kl->keys = nk;
        kl->cap = nc;
    }
    wchar_t *cp = (wchar_t *)malloc(((size_t)n + 1) * 2);
    if (!cp) return;
    memcpy(cp, s, (size_t)n * 2);
    cp[n] = 0;
    kl->keys[kl->count++] = cp;
}

static KeyList *g_keySink = NULL;

static long __cdecl miniFuncCall(void *self, unsigned long flag, const wchar_t *membername,
    unsigned long *hint, Variant *result, int numparams, Variant **param, void *objthis)
{
    (void)self; (void)flag; (void)membername; (void)hint; (void)objthis;
    if (g_keySink && numparams >= 1 && param[0] && param[0]->vt == TVT_STRING && param[0]->u.string) {
        VSString *vs = param[0]->u.string;
        const wchar_t *dp = vs->LongString ? vs->LongString : vs->ShortString;
        int n = vs->Length;
        if (n < 0) n = 0;
        appendKey(g_keySink, dp, n);
    }
    if (result) { result->vt = TVT_INTEGER; result->u.integer = 1; }
    return 0;
}

static long __cdecl miniQueryInterface(void *self, void *iid, void **out)
{ (void)self; (void)iid; if (out) *out = NULL; return 0x80004002; }

static unsigned long __cdecl miniAddRef(void *self) { (void)self; return 2; }

static unsigned long __cdecl miniRelease(void *self) { (void)self; return 1; }

static long __cdecl miniStub(void *self, ...) { (void)self; return 0x80004001; }

static void *miniVtbl[20];
static MiniDispatch miniDispatch;

static void initMiniDispatch(void)
{
    static int done = 0;
    if (done) return;
    done = 1;
    for (int i = 0; i < 20; i++) miniVtbl[i] = (void *)miniStub;
    // 2016-era iTJSDispatch2: [0]=AddRef [1]=Release [2]=FuncCall
    miniVtbl[0] = (void *)miniAddRef;
    miniVtbl[1] = (void *)miniRelease;
    miniVtbl[2] = (void *)miniFuncCall;
    miniDispatch.vtbl = miniVtbl;
}

static void appendUtf8(char **buf, int *len, int *cap, const char *s, int n)
{
    if (*len + n + 1 > *cap) {
        int nc = *cap ? *cap * 2 : 65536;
        while (nc < *len + n + 1) nc *= 2;
        char *nb = (char *)realloc(*buf, (size_t)nc);
        if (!nb) return;
        *buf = nb;
        *cap = nc;
    }
    memcpy(*buf + *len, s, (size_t)n);
    *len += n;
    (*buf)[*len] = 0;
}

static void appendVariantField(char **buf, int *len, int *cap, const Variant *v)
{
    if (!v) { appendUtf8(buf, len, cap, "?", 1); return; }
    if (v->vt == TVT_STRING && v->u.string) {
        VSString *vs = v->u.string;
        const wchar_t *dp = vs->LongString ? vs->LongString : vs->ShortString;
        int n = vs->Length;
        if (n < 0) n = 0;
        char *u8 = utf16ToUtf8(dp, n);
        if (u8) { appendUtf8(buf, len, cap, u8, (int)strlen(u8)); free(u8); }
    } else if (v->vt == TVT_INTEGER) {
        char tmp[32];
        _snprintf(tmp, sizeof(tmp), "%lld", (long long)v->u.integer);
        appendUtf8(buf, len, cap, tmp, (int)strlen(tmp));
    } else if (v->vt == TVT_REAL) {
        char tmp[64];
        _snprintf(tmp, sizeof(tmp), "%g", v->u.real);
        appendUtf8(buf, len, cap, tmp, (int)strlen(tmp));
    } else if (v->vt == TVT_VOID) {
        appendUtf8(buf, len, cap, "", 0);
    } else {
        appendUtf8(buf, len, cap, "?", 1);
    }
}

// runs on the main thread
static void doList(EvalOutcome *outcome)
{
    outcome->ok = 0;
    outcome->result = NULL;
    outcome->error = NULL;
    void *g = g_getScriptDispatch ? g_getScriptDispatch() : NULL;
    if (!g) { outcome->error = _strdup("TJS engine not ready"); return; }
    void **gvtbl = *(void ***)g;
    DispatchPropGetFn gPropGet = (DispatchPropGetFn)gvtbl[4];

    Variant oVar;
    memset(&oVar, 0, sizeof(oVar));
    unsigned long hint = 0;
    if (gPropGet(g, 0, L"o", &hint, &oVar, NULL) != 0 || oVar.vt != TVT_OBJECT || !oVar.u.closure.Object) {
        outcome->error = _strdup("global 'o' not found");
        return;
    }
    void *od = oVar.u.closure.Object;
    void **ovtbl = *(void ***)od;
    // 2016-era iTJSDispatch2 (no QueryInterface): [4]=PropGet, [11]=EnumMembers
    DispatchEnumMembersFn enumMembers = (DispatchEnumMembersFn)ovtbl[11];
    DispatchPropGetFn oPropGet = (DispatchPropGetFn)ovtbl[4];

    initMiniDispatch();
    KeyList kl;
    memset(&kl, 0, sizeof(kl));
    g_keySink = &kl;
    // callback closure: { Object = dispatch to call, ObjThis = NULL }
    void *closure[2] = { &miniDispatch, NULL };
    int erc = enumMembers(od, TJS_ENUM_NO_VALUE, closure, NULL);
    g_keySink = NULL;
    if (erc != 0) {
        char ebuf[128];
        _snprintf(ebuf, sizeof(ebuf), "enumMembers failed rc=%08X", (unsigned int)erc);
        outcome->error = _strdup(ebuf);
        for (int i = 0; i < kl.count; i++) free(kl.keys[i]);
        if (kl.keys) free(kl.keys);
        return;
    }

    if (kl.count <= 0) {
        outcome->result = _strdup("");
        outcome->ok = 1;
        for (int i = 0; i < kl.count; i++) free(kl.keys[i]);
        if (kl.keys) free(kl.keys);
        return;
    }

    char *buf = NULL;
    int blen = 0, bcap = 0;
    void *oObjThis = oVar.u.closure.ObjThis;
    for (int i = 0; i < kl.count; i++) {
        const wchar_t *key = kl.keys[i];
        Variant objVar;
        memset(&objVar, 0, sizeof(objVar));
        hint = 0;
        int rc1 = oPropGet(od, 0, key, &hint, &objVar, oObjThis);
        Variant nv, iv;
        memset(&nv, 0, sizeof(nv));
        memset(&iv, 0, sizeof(iv));
        if (rc1 == 0 && objVar.vt == TVT_OBJECT && objVar.u.closure.Object) {
            void *od2 = objVar.u.closure.Object;
            void **ovtbl2 = *(void ***)od2;
            DispatchPropGetFn p2 = (DispatchPropGetFn)ovtbl2[4];
            void *t2 = objVar.u.closure.ObjThis;
            hint = 0;
            p2(od2, 0, L"name", &hint, &nv, t2);
            hint = 0;
            p2(od2, 0, L"id", &hint, &iv, t2);
        }
        // key \t name \t id \n
        char *k8 = utf16ToUtf8(key, (int)wcslen(key));
        if (k8) { appendUtf8(&buf, &blen, &bcap, k8, (int)strlen(k8)); free(k8); }
        appendUtf8(&buf, &blen, &bcap, "\t", 1);
        appendVariantField(&buf, &blen, &bcap, &nv);
        appendUtf8(&buf, &blen, &bcap, "\t", 1);
        appendVariantField(&buf, &blen, &bcap, &iv);
        appendUtf8(&buf, &blen, &bcap, "\n", 1);
    }
    for (int i = 0; i < kl.count; i++) free(kl.keys[i]);
    if (kl.keys) free(kl.keys);

    outcome->result = buf ? buf : _strdup("");
    outcome->ok = 1;
}



