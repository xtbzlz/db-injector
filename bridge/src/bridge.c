// ---------------------------------------------------------------------------
// logging
// ---------------------------------------------------------------------------
static void logStr(const char *s)
{
    wchar_t path[1100];
    if (!g_logDir[0]) return;
    wsprintfW(path, L"%ls\\tbc_bridge.log", g_logDir);
    HANDLE h = CreateFileW(path, FILE_APPEND_DATA, FILE_SHARE_READ | FILE_SHARE_WRITE,
                           NULL, OPEN_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);
    if (h == INVALID_HANDLE_VALUE) return;
    DWORD written = 0;
    WriteFile(h, s, (DWORD)strlen(s), &written, NULL);
    CloseHandle(h);
}

static void logStrW(const wchar_t *s)
{
    int n = (int)wcslen(s);
    char *buf = (char *)malloc(n * 4 + 1);
    if (!buf) return;
    int j = 0;
    for (int i = 0; i < n; i++) {
        wchar_t c = s[i];
        if (c < 0x80) {
            buf[j++] = (char)c;
        } else if (c < 0x800) {
            buf[j++] = (char)(0xC0 | (c >> 6));
            buf[j++] = (char)(0x80 | (c & 0x3F));
        } else {
            buf[j++] = (char)(0xE0 | (c >> 12));
            buf[j++] = (char)(0x80 | ((c >> 6) & 0x3F));
            buf[j++] = (char)(0x80 | (c & 0x3F));
        }
    }
    buf[j] = 0;
    logStr(buf);
    free(buf);
}

// ---------------------------------------------------------------------------
// UTF conversions (BMP only)
// ---------------------------------------------------------------------------
static wchar_t *utf8ToUtf16(const char *s, int len)
{
    wchar_t *out = (wchar_t *)malloc((len + 1) * 2);
    if (!out) return NULL;
    int j = 0, i = 0;
    while (i < len) {
        unsigned char c = (unsigned char)s[i];
        unsigned int cp;
        int n;
        if (c < 0x80) { cp = c; n = 1; }
        else if ((c & 0xE0) == 0xC0) { cp = c & 0x1F; n = 2; }
        else if ((c & 0xF0) == 0xE0) { cp = c & 0x0F; n = 3; }
        else { cp = c; n = 1; }
        for (int k = 1; k < n; k++) {
            if (i + k >= len) { cp = 0xFFFD; break; }
            cp = (cp << 6) | ((unsigned char)s[i + k] & 0x3F);
        }
        if (cp > 0xFFFF) cp = 0xFFFD;
        out[j++] = (wchar_t)cp;
        i += n;
    }
    out[j] = 0;
    return out;
}

static char *utf16ToUtf8(const wchar_t *s, int len)
{
    char *out = (char *)malloc(len * 3 + 1);
    if (!out) return NULL;
    int j = 0;
    for (int i = 0; i < len; i++) {
        unsigned int c = (unsigned int)s[i];
        if (c < 0x80) out[j++] = (char)c;
        else if (c < 0x800) {
            out[j++] = (char)(0xC0 | (c >> 6));
            out[j++] = (char)(0x80 | (c & 0x3F));
        } else {
            out[j++] = (char)(0xE0 | (c >> 12));
            out[j++] = (char)(0x80 | ((c >> 6) & 0x3F));
            out[j++] = (char)(0x80 | (c & 0x3F));
        }
    }
    out[j] = 0;
    return out;
}

// ---------------------------------------------------------------------------
// TVPDoTryBlock callbacks (cdecl)
// ---------------------------------------------------------------------------
typedef struct _TryData {
    TJSString ttstr;
    TJSString name;
    Variant result;
    char *error; // malloc'd utf8
} TryData;

static void __cdecl tryBlock(void *data)
{
    TryData *d = (TryData *)data;
    if (g_executeExpression) g_executeExpression(&d->ttstr, &d->result);
}

// script-mode try block (multi-statement scripts via TVPExecuteScript,
// which takes the script text directly - no storage file needed)
static void __cdecl tryBlockScript(void *data)
{
    TryData *d = (TryData *)data;
    if (g_executeScript) g_executeScript(&d->ttstr, &d->name, 0, &d->result);
}

static int __cdecl catchBlock(void *data, const TVPExceptionDesc *desc)
{
    TryData *d = (TryData *)data;
    if (desc->message.Ptr) {
        VSString *vs = desc->message.Ptr;
        const wchar_t *dataPtr = vs->LongString ? vs->LongString : vs->ShortString;
        int n = vs->Length;
        if (n < 0) n = 0;
        d->error = utf16ToUtf8(dataPtr, n);
    } else {
        d->error = _strdup("unknown TJS exception");
    }
    return 0; // swallow
}

